/**
 * ReactFlow 用の nodes と edges を生成する。
 * レイアウトは getPipelineLayout() (layoutEngine.js) で適用する。
 */
export const buildPipelineGraph = () => {
  const pipelineNodes = PIPELINE_NODES.map((n) => ({
    id: n.id,
    type: 'pipeline',
    position: { x: 0, y: 0 }, // layoutEngine で上書きされる
    data: n,
    draggable: false,
  }));

  const pipelineEdges = [];
  PIPELINE_NODES.forEach(n => {
    (n.dependencies || []).forEach(dep => {
      pipelineEdges.push({
        id: `${dep}-${n.id}`,
        source: dep,
        target: n.id,
        type: 'smoothstep',
        animated: true,
        style: { stroke: '#374151', strokeWidth: 2 },
        markerEnd: { type: 'arrowclosed', width: 16, height: 16, color: '#6b7280' },
      });
    });
  });

  return { pipelineNodes, pipelineEdges };
};
